// PreToolUse hook for Edit and Write: refuses edits to files that must not be changed by hand.
// It does not see shell commands, so it is a guard against mistakes, not a security boundary.
import { spawnSync } from 'node:child_process';
import { dirname, relative, resolve } from 'node:path';
import { block, readHookInput, repoRoot } from './lib.mjs';

const input = await readHookInput();
const file = input.tool_input?.file_path;
if (!file) process.exit(0);

const absolute = resolve(input.cwd ?? process.cwd(), file);
const root = repoRoot(dirname(absolute));
if (!root) process.exit(0);
const path = relative(root, absolute).replaceAll('\\', '/');

if (/^(android|ios)\//.test(path)) {
  block(
    `Blocked: ${path} is generated by prebuild: change native config through app.json and config plugins.`,
  );
}

// A migration that is already on main may be applied to production, so it never changes again.
if (/^supabase\/migrations\/.+\.sql$/.test(path)) {
  const onMain = spawnSync('git', ['cat-file', '-e', `origin/main:${path}`], { cwd: root });
  if (onMain.status === 0) {
    block(
      `Blocked: ${path} is already on origin/main, so production may have applied it. ` +
        'Add a new migration with `pnpm db:new <name>` instead.',
    );
  }
}
